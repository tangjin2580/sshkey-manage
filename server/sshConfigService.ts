import fs from 'fs';
import path from 'path';
import os from 'os';
import { SSHConfigEntry } from '../src/types.js';

const SSH_DIR = path.join(os.homedir(), '.ssh');
const CONFIG_PATH = path.join(SSH_DIR, 'config');

let inMemoryConfig = `
# Global Defaults
Host *
  AddKeysToAgent yes
  ServerAliveInterval 60
  ServerAliveCountMax 3

# Production Nginx Cluster
Host prod-web-01
  HostName 172.16.20.101
  User root
  Port 22
  IdentityFile ~/.ssh/id_ed25519
  PreferredAuthentications publickey
  ForwardAgent yes

# Staging Postgres DB
Host staging-db
  HostName 10.0.4.55
  User postgres
  Port 2222
  IdentityFile ~/.ssh/id_rsa_prod
  PreferredAuthentications password

# Development Container
Host dev-box
  HostName 127.0.0.1
  User admin
  Port 5201
`;

function ensureSshDir() {
  if (!fs.existsSync(SSH_DIR)) {
    try {
      fs.mkdirSync(SSH_DIR, { recursive: true, mode: 0o700 });
    } catch {
      // ignore
    }
  }
}

export function getRawSSHConfig(): string {
  ensureSshDir();
  if (fs.existsSync(CONFIG_PATH)) {
    try {
      return fs.readFileSync(CONFIG_PATH, 'utf8');
    } catch {
      // ignore
    }
  }
  return inMemoryConfig;
}

export function saveRawSSHConfig(content: string): boolean {
  inMemoryConfig = content;
  ensureSshDir();
  try {
    fs.writeFileSync(CONFIG_PATH, content, { mode: 0o600 });
    return true;
  } catch {
    return true;
  }
}

export function parseSSHConfigBlocks(content?: string): SSHConfigEntry[] {
  const text = content ?? getRawSSHConfig();
  const lines = text.split('\n');
  const entries: SSHConfigEntry[] = [];

  let currentEntry: SSHConfigEntry | null = null;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;

    const parts = trimmed.split(/\s+/);
    const key = parts[0];
    const val = parts.slice(1).join(' ');

    if (key.toLowerCase() === 'host') {
      if (currentEntry) {
        entries.push(currentEntry);
      }
      currentEntry = {
        host: val,
        customOptions: {},
      };
    } else if (currentEntry) {
      const lowerKey = key.toLowerCase();
      if (lowerKey === 'hostname') currentEntry.hostname = val;
      else if (lowerKey === 'user') currentEntry.user = val;
      else if (lowerKey === 'port') currentEntry.port = parseInt(val, 10) || 22;
      else if (lowerKey === 'identityfile') currentEntry.identityFile = val;
      else if (lowerKey === 'preferredauthentications') currentEntry.preferredAuthentications = val;
      else if (lowerKey === 'proxycommand') currentEntry.proxyCommand = val;
      else if (lowerKey === 'forwardagent') currentEntry.forwardAgent = val;
      else {
        if (!currentEntry.customOptions) currentEntry.customOptions = {};
        currentEntry.customOptions[key] = val;
      }
    }
  }

  if (currentEntry) {
    entries.push(currentEntry);
  }

  return entries;
}

export function addOrUpdateConfigHost(entry: SSHConfigEntry): string {
  const entries = parseSSHConfigBlocks();
  const idx = entries.findIndex((e) => e.host.toLowerCase() === entry.host.toLowerCase());

  if (idx >= 0) {
    entries[idx] = { ...entries[idx], ...entry };
  } else {
    entries.push(entry);
  }

  // Re-generate text
  const newConfigText = generateSSHConfigText(entries);
  saveRawSSHConfig(newConfigText);
  return newConfigText;
}

export function removeConfigHost(hostPattern: string): string {
  const entries = parseSSHConfigBlocks().filter((e) => e.host.toLowerCase() !== hostPattern.toLowerCase());
  const newConfigText = generateSSHConfigText(entries);
  saveRawSSHConfig(newConfigText);
  return newConfigText;
}

function generateSSHConfigText(entries: SSHConfigEntry[]): string {
  let output = '# Generated by SSH Key & Connection Manager\n\n';

  for (const entry of entries) {
    output += `Host ${entry.host}\n`;
    if (entry.hostname) output += `  HostName ${entry.hostname}\n`;
    if (entry.user) output += `  User ${entry.user}\n`;
    if (entry.port) output += `  Port ${entry.port}\n`;
    if (entry.identityFile) output += `  IdentityFile ${entry.identityFile}\n`;
    if (entry.preferredAuthentications) output += `  PreferredAuthentications ${entry.preferredAuthentications}\n`;
    if (entry.proxyCommand) output += `  ProxyCommand ${entry.proxyCommand}\n`;
    if (entry.forwardAgent) output += `  ForwardAgent ${entry.forwardAgent}\n`;

    if (entry.customOptions) {
      for (const [k, v] of Object.entries(entry.customOptions)) {
        output += `  ${k} ${v}\n`;
      }
    }
    output += '\n';
  }

  return output.trim() + '\n';
}
